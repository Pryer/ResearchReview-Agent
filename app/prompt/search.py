"""检索关键词生成与反馈修正 Prompt。"""

SEARCH_KEYWORD_GENERATION_PROMPT = """\
你是学术论文检索 Agent 的查询规划模块。
请根据用户请求和研究主题，生成适合论文数据库检索的中英文关键词。

要求：
- 覆盖该研究领域的中文名称、英文标准术语、常用同义表达和任务/方法变体。
- 英文关键词优先使用学术论文标题和摘要中常见的表达。
- 先根据用户原文判断主题是边界明确的窄主题，还是包含多个子问题、研究范式或应用语境的宽主题；该判断只用于规划，不要输出额外解释。
- 对窄主题，保持任务边界，优先生成标准术语、缩写和高价值同义词，不得为了多样性扩展到相邻领域。
- 对宽主题，从用户主题本身推导彼此不同的检索视角，使查询集合覆盖主要研究脉络；不得预设任何固定学科分类，也不得把全部检索位分配给同一子任务或同义方法。
- 查询之间应具有互补召回价值。语义近似、只是替换单个近义词的查询最多保留一个。
- 不要生成脱离主题、单独使用时含义过宽的词。
- 不要编造不存在的领域术语。
- 返回 3 到 5 个关键词，按检索优先级排序。
- 关键词必须精准，不要返回中文“论文/综述”后缀词。
- 英文关键词应为 2 到 4 个单词构成的标准学术短语（如 "knowledge graph completion"、"medical image segmentation" 等），切忌把多个不相关词汇或句子长串拼接。
- 第一个关键词必须是研究主题本身。
- 把主题拆成 1 到 2 个核心概念组（不要超过2组）；每组列出中英文同义词。
- 每个核心概念组必须同时包含中文术语和英文术语；缺少任一语言术语的概念组会被系统判无效并丢弃。
- 第一个核心概念组必须保留研究主题的锚点对象或核心现象，不能用其下游结果、应用效果、宽泛场景词或常见研究方法替代主题本身。
- 用户选择了某一消歧范围时，范围词用于限定该锚点的学科含义；不得把范围说明中的任意关联变量升级成主题锚点。
- topic_anchors 仅供后续词法打分和检索规划使用，不得用作逐论文硬纳入条件。
- 不要生成 excluded_title_terms。自动排除词极易误杀跨领域/比较型/统一框架型论文。

请严格返回 JSON：
{{
  "keywords": ["关键词1", "keyword 2"],
  "topic_anchors": [
    {{"concept": "核心概念1", "terms": ["中文术语", "English synonym"]}},
    {{"concept": "核心概念2", "terms": ["中文术语", "English synonym"]}}
  ]
}}

用户请求：{user_query}
研究主题：{topic}
"""

